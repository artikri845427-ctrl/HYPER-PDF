# Builds HyperPDF-Setup-<version>.exe with Inno Setup.
#
# The script reads the branding from Directory.Build.props, generates brand.iss and calls the
# Inno Setup compiler. The application and the native Shell extensions have to be built
# before (tools\build-app.ps1 and tools\build-native.ps1).

[CmdletBinding()]
param(
    [string]$Configuration = 'Release',
    [string]$InnoSetupPath = '',
    [switch]$SkipAppBuild,
    [switch]$SkipNativeBuild
)

$ErrorActionPreference = 'Stop'

$repoRoot = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$installerDirectory = Join-Path $repoRoot 'installer'
$propsFile = Join-Path $repoRoot 'Directory.Build.props'
$outputDirectory = Join-Path $repoRoot 'build\installer'

function Write-Step([string]$Message) {
    Write-Host "==> $Message" -ForegroundColor Cyan
}

function Get-PropValue([string]$Content, [string]$Name) {
    $match = [regex]::Match($Content, "<$Name>([^<]*)<")
    if (-not $match.Success) {
        return $null
    }

    return [System.Net.WebUtility]::HtmlDecode($match.Groups[1].Value)
}

function Resolve-InnoSetup {
    if ($InnoSetupPath -and (Test-Path -LiteralPath $InnoSetupPath)) {
        return $InnoSetupPath
    }

    $candidates = @(
        (Join-Path ${env:ProgramFiles(x86)} 'Inno Setup 6\ISCC.exe'),
        (Join-Path $env:ProgramFiles 'Inno Setup 6\ISCC.exe')
    )

    foreach ($candidate in $candidates) {
        if (Test-Path -LiteralPath $candidate) {
            return $candidate
        }
    }

    $command = Get-Command ISCC.exe -ErrorAction SilentlyContinue
    if ($command) {
        return $command.Source
    }

    throw 'Inno Setup 6 was not found. Install it or pass -InnoSetupPath.'
}

# --------------------------------------------------------------------------------------------
# Branding
# --------------------------------------------------------------------------------------------
$props = Get-Content -LiteralPath $propsFile -Raw -Encoding UTF8

$productName = Get-PropValue $props 'HyperPdfProductName'
$version = Get-PropValue $props 'HyperPdfVersion'
$company = Get-PropValue $props 'HyperPdfCompany'
$author = Get-PropValue $props 'HyperPdfAuthor'
$copyright = Get-PropValue $props 'HyperPdfCopyright'
$contact = Get-PropValue $props 'HyperPdfContact'
$repository = Get-PropValue $props 'HyperPdfRepository'

if (-not $productName -or -not $version) {
    throw "The branding could not be read from '$propsFile'."
}

$brand = @"
; Generated by installer\build-installer.ps1 - do not edit.
#define BrandFileIncluded
#define Brand_ProductName "$productName"
#define Brand_Version "$version"
#define Brand_Company "$company"
#define Brand_Publisher "$author"
#define Brand_Author "$author"
#define Brand_Copyright "$copyright"
#define Brand_Contact "$contact"
#define Brand_RepositoryUrl "$repository"
#define Brand_Description "$productName is a fast, modern Windows PDF reader with native Explorer thumbnail and preview support."
#define Brand_CreditLine "Developed by $author | Contact: $contact"
#define Brand_AppId "{{9C6F1B27-5F3E-4E4C-9F5A-1B2C3D4E5F60}}"
"@

$brandFile = Join-Path $installerDirectory 'brand.iss'
Set-Content -LiteralPath $brandFile -Value $brand -Encoding UTF8
Write-Step "The branding was written to '$brandFile'"

# --------------------------------------------------------------------------------------------
# Build the artefacts
# --------------------------------------------------------------------------------------------
if (-not $SkipAppBuild) {
    Write-Step 'Building the application'
    & (Join-Path $repoRoot 'tools\build-app.ps1') -Configuration $Configuration
    if ($LASTEXITCODE -ne 0) {
        throw 'The application build failed.'
    }
}

if (-not $SkipNativeBuild) {
    Write-Step 'Building the native Shell extensions'
    & (Join-Path $repoRoot 'tools\build-native.ps1') -Configuration $Configuration
    if ($LASTEXITCODE -ne 0) {
        throw 'The native build failed.'
    }
}

# --------------------------------------------------------------------------------------------
# Compile the installer
# --------------------------------------------------------------------------------------------
$iscc = Resolve-InnoSetup
New-Item -ItemType Directory -Path $outputDirectory -Force | Out-Null

Write-Step "Compiling the installer with $iscc"
& $iscc (Join-Path $installerDirectory 'HyperPDF.iss')
if ($LASTEXITCODE -ne 0) {
    throw "The Inno Setup compiler failed with exit code $LASTEXITCODE."
}

$installer = Join-Path $outputDirectory "$productName-Setup-$version.exe"
if (-not (Test-Path -LiteralPath $installer)) {
    throw "The installer '$installer' was not created."
}

Write-Step "The installer is available: $installer ($([math]::Round((Get-Item $installer).Length / 1MB, 1)) MB)" -ForegroundColor Green
Write-Step $copyright
